'use client';
import { useState } from 'react';
import { useInsight } from '@/hooks/useInsight';

interface Props {
  userId: string | null;
}

// AI Analyst — user-triggered portfolio insight.
export function PortfolioInsight({ userId }: Props) {
  const { data, loading, error, generate } = useInsight(userId);
  const [hyperliquidAddress, setHyperliquidAddress] = useState('');

  if (!userId) return null;

  return (
    <div className="rounded-lg border border-white/10 bg-black/20 p-5">
      <div className="flex items-center justify-between gap-3">
        <div>
          <h2 className="text-lg font-semibold text-white">AI Analyst</h2>
          <p className="text-xs text-white/60">
            Natural-language analysis of your current portfolio
          </p>
        </div>
        <button
          onClick={() => generate(hyperliquidAddress)}
          disabled={loading}
          className="rounded-md border border-white/20 bg-white/10 px-4 py-2 text-sm font-medium text-white hover:bg-white/20 disabled:opacity-50"
        >
          {loading ? 'Analyzing…' : data ? 'Regenerate' : 'Analyze Portfolio'}
        </button>
      </div>

      <div className="mt-3">
        <label className="flex flex-col gap-1 text-xs text-white/60">
          Hyperliquid Address (optional — for perps exposure context)
          <input
            type="text"
            spellCheck={false}
            autoComplete="off"
            className="rounded-md border border-white/20 bg-white/95 px-3 py-2 font-mono text-xs text-black focus:border-portfolio-yellow focus:outline-none focus:ring-2 focus:ring-portfolio-yellow/50"
            placeholder="0x..."
            value={hyperliquidAddress}
            onChange={(e) => setHyperliquidAddress(e.target.value)}
          />
        </label>
      </div>

      {error && (
        <div className="mt-4 rounded-md border border-red-500/40 bg-red-500/10 px-3 py-2 text-sm text-red-200">
          {error}
        </div>
      )}
      {data && !loading && (
        <div className="mt-4 space-y-3">
          <div className="whitespace-pre-wrap text-sm leading-relaxed text-white/90">
            {data.insight}
          </div>
          <div className="text-xs text-white/50">
            Generated {new Date(data.generatedAt).toLocaleString()} · {data.model}
          </div>
          <div className="text-xs text-white/60 border border-white/10 rounded-md px-3 py-2 mt-2">
            This analysis is generated by AI from your current portfolio positions. It does not account for your financial goals, risk tolerance, or full financial situation and is not financial advice.
          </div>
        </div>
      )}
    </div>
  );
}